"""Q. why YOLO V8 has Less Fitness Score than YOLOv5?

Ans - YOLO V5uses Anchor Boxes (pre-defined shapes that "guess" where a helmet might be). This gives it a "head start" in the early stages of training because it’s looking for specific boxes.
YOLOv8 is Anchor-Free. It predicts the center of an object directly. While this is more accurate in the long run, it takes more epochs to "learn" how to draw those boxes precisely. If you only trained for 50 epochs, YOLOv8 might just need more time to stabilize.

1. YOLOv8 is designed to capture more "features" (like the strap of the helmet or the reflection on the visor).

2. The Result: Because it's looking for more detail, it can sometimes produce more "False Positives" early on, which brings the fitness score down until the model fine-tunes itself.
"""

