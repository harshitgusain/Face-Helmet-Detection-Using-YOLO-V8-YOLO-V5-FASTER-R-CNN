torch_class_map = {"background": 0, "with helmet": 1, "without helmet": 2}

class HelmetTorchDataset(torch.utils.data.Dataset):
    def __init__(self, img_dir, annot_dir):
        self.img_dir = img_dir
        self.annot_dir = annot_dir
        self.imgs = sorted([f for f in os.listdir(img_dir) if f.endswith('.png')])

    def __getitem__(self, idx):
        img_path = os.path.join(self.img_dir, self.imgs[idx])
        xml_path = os.path.join(self.annot_dir, self.imgs[idx].replace('.png', '.xml'))

        img = Image.open(img_path).convert("RGB")
        img_tensor = T.ToTensor()(img)

        tree = ET.parse(xml_path)
        root = tree.getroot()
        boxes, labels = [], []

        for obj in root.findall('object'):
            name = obj.find('name').text.lower().strip()
            labels.append(torch_class_map[name])
            bb = obj.find('bndbox')
            boxes.append([float(bb.find('xmin').text), float(bb.find('ymin').text),
                          float(bb.find('xmax').text), float(bb.find('ymax').text)])

        target = {
            "boxes": torch.as_tensor(boxes, dtype=torch.float32),
            "labels": torch.as_tensor(labels, dtype=torch.int64),
            "image_id": torch.tensor([idx])
        }
        return img_tensor, target

    def __len__(self):
        return len(self.imgs)

